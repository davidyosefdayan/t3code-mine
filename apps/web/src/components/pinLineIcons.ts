const BY_NAME = new Map(PIN_LINE_ICONS);

// Colors a line icon can take; emoji keep their own. Values are stored as
// "icon:<name>" or "icon:<name>@<color>".
export const PIN_ICON_COLORS = {
  gray: "text-muted-foreground",
  brown: "text-amber-800 dark:text-amber-600",
  orange: "text-orange-600 dark:text-orange-400",
  yellow: "text-yellow-600 dark:text-yellow-400",
  green: "text-emerald-600 dark:text-emerald-400",
  blue: "text-sky-600 dark:text-sky-400",
  purple: "text-violet-600 dark:text-violet-400",
  pink: "text-pink-600 dark:text-pink-400",
  red: "text-red-600 dark:text-red-400",
} as const;

export type PinIconColor = keyof typeof PIN_ICON_COLORS;

export function isPinIconColor(value: string): value is PinIconColor {
  return Object.hasOwn(PIN_ICON_COLORS, value);
}

export function pinLineIcon(
  value: string,
): { name: string; Icon: LucideIcon; color: PinIconColor | null } | null {
  if (!value.startsWith("icon:")) return null;
  const [name = "", color = ""] = value.slice(5).split("@");
  const Icon = BY_NAME.get(name);
  if (Icon === undefined) return null;
  return { name, Icon, color: isPinIconColor(color) ? color : null };
}

export function pinLineIconValue(name: string, color: PinIconColor | null): string {
  return color === null ? `icon:${name}` : `icon:${name}@${color}`;
}
